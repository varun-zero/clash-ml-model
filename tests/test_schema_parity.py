"""Guards the failure mode shape-only tests cannot catch: producers disagreeing on
what channel/scalar index N MEANS, label leakage, and hand/action misalignment."""
import json
import pytest
import numpy as np
from configs.observation_schema import Ch, Sc, SCHEMA_VERSION, check_schema
from configs.constants import CARD_NAME_TO_ID
from perception.state_encoder import StateEncoder
from tools.ingest_vanguard_replays import process_match, card_key_to_id

NAMES = ["arrows", "fireball", "knight", "archers", "goblins", "spear goblins", "giant", "minions"]


def _valid_sequence(n=12, seed=0):
    """Plays generated by simulating the REAL 4-slot hand + 4-card queue cycle."""
    rng = np.random.RandomState(seed)
    order = list(rng.permutation(NAMES))
    hand, queue, seq = order[:4], order[4:], []
    for _ in range(n):
        s_ = int(rng.randint(4))
        c = hand[s_]
        seq.append(c)
        hand[s_] = queue.pop(0)
        queue.append(c)
    return seq


SEQ = _valid_sequence()


def _replay():
    deck = [{"card_key": n.replace(" ", "-")} for n in NAMES]
    meta = {"result": "victory", "payload_json": json.dumps({"battle": {"team": {"players": [{"deck": deck}]}}})}
    acts, t = [], 5.0
    for i, n in enumerate(SEQ):
        acts.append(dict(side="team", kind="play_card", card_key=n.replace(" ", "-"), grid_x=5 + i, grid_y=8 + i, time_seconds=t))
        t += 6
    return meta, acts


def test_no_target_leakage_and_hand_alignment():
    out = process_match(*_replay())
    assert out is not None
    for k, nm in enumerate(SEQ[: len(out["action_card"])]):
        slot = int(out["action_card"][k]) - 1
        assert int(out["hand_ids"][k][slot]) == CARD_NAME_TO_ID[nm], "hand[slot] must be the card actually played"
        ty, tx = divmod(int(out["action_tile"][k]), 18)
        last = out["arena_grid"][k][-8:]
        assert last[Ch.ALLY_GROUND, ty, tx] == 0 and last[Ch.SPELL, ty, tx] == 0, "target tile must not be in the input"


def test_vanguard_scalars_follow_live_encoder_layout():
    out = process_match(*_replay())
    _, live, _ = StateEncoder().encode(detections=[], elixir=5.0, hand_card_ids=[20, 21, 24, 2],
                                       tower_hps=[1] * 6, time_left=170.0, last_action=(0, 0))
    v = out["scalars"][0]
    assert v[Sc.TIME_LEFT] > 0.9 and live[Sc.TIME_LEFT] > 0.9          # same meaning at same index
    assert np.all(v[Sc.ALLY_KING:Sc.ENEMY_RIGHT + 1] == 1.0)
    assert v[Sc.DOUBLE_ELIXIR] == 0.0                                   # idx 11 is double-elixir, never the outcome label
    live_grid, _, _ = StateEncoder().encode(detections=[], elixir=5.0, hand_card_ids=[20, 21, 24, 2])
    assert np.array_equal(out["arena_grid"][0][-8:][Ch.DEPLOYABLE], live_grid[Ch.DEPLOYABLE])


def test_unreconstructable_hand_is_rejected_not_guessed():
    meta, acts = _replay()
    acts[2]["card_key"] = "hog-rider"            # card not in the deck -> impossible sequence
    assert process_match(meta, acts) is None


def test_card_key_normalization_xbow_and_minipekka():
    """Verify alphanumeric card normalization correctly maps hyphenated cards."""
    xbow_id = card_key_to_id("x-bow")
    mini_pekka_id = card_key_to_id("mini-pekka")
    log_id = card_key_to_id("the-log")
    ev_id = card_key_to_id("firecracker-ev1")

    assert xbow_id > 0, f"Expected non-zero id for 'x-bow', got {xbow_id}"
    assert mini_pekka_id > 0, f"Expected non-zero id for 'mini-pekka', got {mini_pekka_id}"
    assert log_id > 0, f"Expected non-zero id for 'the-log', got {log_id}"
    assert ev_id > 0, f"Expected non-zero id for 'firecracker-ev1', got {ev_id}"
    assert xbow_id == CARD_NAME_TO_ID["x-bow"]
    assert mini_pekka_id == CARD_NAME_TO_ID["mini p.e.k.k.a"]


def test_strict_schema_enforcement():
    """Verify check_schema strictly rejects shards missing schema_version or with version mismatch."""
    with pytest.raises(ValueError, match="missing schema_version"):
        check_schema({"scalars": np.zeros(12)}, path="legacy_shard.npz")

    with pytest.raises(ValueError, match="schema_version=1"):
        check_schema({"schema_version": 1}, path="old_shard.npz")

    # Valid schema_version must not raise
    check_schema({"schema_version": SCHEMA_VERSION}, path="valid_shard.npz")
