    # ------------------------------------------------------------ legality
    def _is_unit_card(self, cm: dict) -> bool:
        return bool(cm.get("SummonCharacter"))

    def legal_action(self, team: int, hand_idx: int, x: float, y: float) -> bool:
        if self.done or not (0 <= hand_idx < len(self.hand[team])):
            return False
        card = self.hand[team][hand_idx]
        if self.elixir[team] < self.card_cost(card) or self.play_cd[team] > 0:
            return False
        cm = self._card_meta(card)
        if not (0 <= x <= ARENA_W and 0 <= y <= ARENA_H):
            return False
        if card == "Mirror" and not self.last_played[team]:
            return False
        if self._is_unit_card(cm) and not cm.get("CanDeployOnEnemySide"):
            if not self._own_half_ok(team, x, y):
                return False
        return True

    def _own_half_ok(self, team: int, x: float, y: float) -> bool:
        if team == 0 and y > RIVER_Y - RIVER_HALF:
            return False
        if team == 1 and y < RIVER_Y + RIVER_HALF:
            return False
        bdef = self.model.get("buildings", {})
        for u in self.units:
            if u.hp <= 0 or not (u.is_building or isinstance(u, Tower)):
                continue
            d = bdef.get(u.name, {})
            w = (d.get("NoDeploySizeW") or 0) / 2.0
            h = (d.get("NoDeploySizeH") or 0) / 2.0
            if w and h and abs(x - u.x) <= w / 2 and abs(y - u.y) <= h / 2:
                return False
        return True

    # ------------------------------------------------------------- actions
    def play(self, team: int, hand_idx: int, x: float, y: float) -> bool:
        if not self.legal_action(team, hand_idx, x, y):
            return False
        card = self.hand[team][hand_idx]
        cost = self.card_cost(card)
        self.elixir[team] -= cost
        self.play_cd[team] = CARD_PLAY_COOLDOWN_MS

        cm = self._card_meta(card)
        if card == "Mirror":
            src = self.last_played[team]
            if src:
                self._replay_mirrored(team, src, x, y)
        else:
            self._deploy_card(team, cm, x, y)
        self.last_played[team] = card
        played = self.hand[team][hand_idx]
        self.hand[team][hand_idx] = self.cycle[team][0]
        self.cycle[team].append(played)
        self.cycle[team].pop(0)
        return True

    def _deploy_card(self, team: int, cm: dict, x: float, y: float,
                     level_bonus: int = 0):
        summon = cm.get("SummonCharacter") or ""
        sdef = ((self.model.get("buildings", {}).get(summon)
                 or self.model.get("characters", {}).get(summon)) or {})
        summon_is_spell = (summon in self.model.get("buildings", {})
                           and not sdef.get("Hitpoints")
                           and sdef.get("DeathAreaEffect"))
        if summon and not summon_is_spell:
            n = int(cm.get("SummonNumber") or 1)
            cols = max(1, int(cm.get("SummonWidth") or min(n, 3)))
            if summon in self.model.get("buildings", {}):
                self._place(summon, team, x, y, level_bonus=level_bonus)
            else:
                for i in range(n):
                    px = x + (i % cols - (cols - 1) / 2.0) * 1.0
                    py = y + (i // cols) * 1.0
                    self._place(summon, team, px, py, level_bonus=level_bonus)
            second = cm.get("SummonCharacterSecond") or ""
            if second:
                n2 = int(cm.get("SummonCharacterSecondCount") or 1)
                cols2 = max(1, min(n2, 3))
                for i in range(n2):
                    px = x + (i % cols2 - (cols2 - 1) / 2.0) * 1.0
                    py = y + 1.2 + (i // cols2) * 1.0
                    self._place(second, team, px, py, level_bonus=level_bonus)
        else:
            self._cast_spell(cm, team, x, y, level_bonus=level_bonus)

    def _replay_mirrored(self, team: int, card: str, x: float, y: float):
        cm = self._card_meta(card)
        self._deploy_card(team, cm, x, y, level_bonus=1)

    def _place(self, name: str, team: int, x: float, y: float,
               level_bonus: int = 0):
        bdef = self.model.get("buildings", {}).get(name)
        if bdef:
            return self._sp_unit(name, team, x, y, building=True, defdict=bdef,
                                 level=None if not level_bonus else
                                 self.card_level + level_bonus)
        cdef = self.model.get("characters", {}).get(name)
        if cdef:
            return self._sp_unit(name, team, x, y, building=False, defdict=cdef,
                                 level=None if not level_bonus else
                                 self.card_level + level_bonus)
        return None

    # ------------------------------------------------------------- spells
    def _spell_projectile_damage(self, pdef: dict, team: int, x: float, y: float,
                                 level_bonus: int = 0, cm: dict | None = None):
        """Apply a spell projectile hit instantly at (x, y).

        Used for spell cards whose payload is a projectile (Fireball, Rocket,
        Snowball, Arrows, GoblinBarrel, BarbLog, ...).  Handles splash damage,
        tower-damage reduction, target buffs, pushback, character spawns and
        chained projectile payloads.
        """
        pname = pdef.get("Name") or ""
        radius = _num(pdef.get("Radius") or (cm or {}).get("Radius")) / 1000.0
        dmg = pdef.get("Damage")
        tdmg = pdef.get("TowerDamage")
        if isinstance(dmg, dict):
            tdmg = dmg.get("TowerDamage", tdmg)
            dmg = dmg.get("BaseDamage", 0)
        if dmg is None and cm:
            dmg = cm.get("InstantDamage")
        lvl = self.card_level + level_bonus
        if not isinstance(dmg, (int, float)) or dmg <= 0:
            # pure utility projectile: still process spawns/buffs/chain
            self._projectile_payload(pdef, team, x, y, radius, [], level_bonus)
            return
        dmg = _growth(int(dmg), lvl, self.card_dmg_pct)
        crown_pct = _num(pdef.get("CrownTowerDamagePercent"))
        tower_dmg = _growth(int(tdmg), lvl, self.card_dmg_pct) if tdmg else \
            max(1, int(dmg * (1 + crown_pct / 100.0)))
        hits = [u for u in self.units
                if u.team != team and u.hp > 0
                and math.hypot(u.x - x, u.y - y) <= radius + u.col_t]
        for u in hits:
            self._damage(u, tower_dmg if isinstance(u, Tower) else dmg)
        self._projectile_payload(pdef, team, x, y, radius, hits, level_bonus)
        # pushback
        pb = _num(pdef.get("Pushback")) / 1000.0
        if pb:
            self._pushback_from(x, y, radius, pb, team)

    def _projectile_payload(self, pdef: dict, team: int, x: float, y: float,
                            radius: float, hits: list, level_bonus: int = 0,
                            depth: int = 0):
        """Buffs / spawns / sub-AEO / chained projectiles carried by a projectile."""
        buff = pdef.get("TargetBuff") or pdef.get("Buff") or ""
        btime = int(pdef.get("BuffTime") or 0)
        if buff:
            for u in hits:
                self._apply_buff(u, buff, btime or 1000, team)
        # sub area effect (heal spirit heal, ice spirit evo freeze field, ...)
        sub = pdef.get("SpawnAreaEffectObject")
        if isinstance(sub, str):
            ae = self.aeo.get(sub)
            if ae:
                self._spawn_area_field(sub, ae, team, x, y, level_bonus=level_bonus)
        # chained lightning (electro spirit / electro dragon / zap spirit)
        cnt = int(pdef.get("ChainedHitCount") or 0)
        if cnt > 0 and depth < 3:
            chain_r = _num(pdef.get("ChainedHitRadius")) / 1000.0
            dmg = pdef.get("Damage")
            if isinstance(dmg, dict):
                dmg = dmg.get("BaseDamage", 0)
            already = {u.id for u in hits}
            pool = sorted((u for u in self.units
                           if u.hp > 0 and u.team != team and u.id not in already
                           and math.hypot(u.x - x, u.y - y) <= chain_r + u.col_t),
                          key=lambda u: math.hypot(u.x - x, u.y - y))
            for u in pool[:cnt]:
                if isinstance(dmg, (int, float)) and dmg > 0:
                    self._damage(u, _growth(int(dmg), self.card_level + level_bonus,
                                            self.card_dmg_pct))
                if buff:
                    self._apply_buff(u, buff, btime or 1000, team)
        # spawn characters (goblin barrel, royal delivery recruit, barb barrel)
        sc = pdef.get("SpawnCharacter")
        if sc and depth < 3:
            n = int(pdef.get("SpawnCharacterCount") or 1)
            delay = int(pdef.get("SpawnCharacterDeployTime") or 1000)
            for i in range(n):
                px = x + (i - (n - 1) / 2.0) * 0.6
                u = self._place(sc, team, px, y, level_bonus=level_bonus)
                if u:
                    u.load_ms = delay
        # chained projectile payload (firecracker shards / barb barrel roll)
        subp = pdef.get("SpawnProjectile")
        if isinstance(subp, str) and depth < 2:
            self._spawn_chain_projectiles(pdef, subp, team, x, y, level_bonus,
                                          depth + 1)

    def _spawn_chain_projectiles(self, pdef: dict, subp: str, team: int,
                                 x: float, y: float, level_bonus: int,
                                 depth: int, ang: float | None = None):
        subdef = self.model.get("projectiles", {}).get(subp) or {}
        if not subdef:
            return
        n = int(subdef.get("SpawnCount") or pdef.get("SpawnCount")
                or pdef.get("SpawnProjectileCount") or 1)
        n = max(1, min(n, 12))
        speed = _num(subdef.get("Speed")) * PROJECTILE_TILE_S_PER_UNIT
        if speed <= 0:
            speed = 6.0
        rng_t = _num(subdef.get("ProjectileRange")) / 1000.0 or 2.0
        radius = _num(subdef.get("Radius")
                      or subdef.get("ProjectileRadius")) / 1000.0
        dmg = subdef.get("Damage")
        if isinstance(dmg, dict):
            dmg = dmg.get("BaseDamage", 0)
        dmg = _growth(int(dmg or 0), self.card_level + level_bonus,
                      self.card_dmg_pct) if dmg else 0
        crown = _num(subdef.get("CrownTowerDamagePercent"))
        tdm = max(1, int(dmg * (1 + crown / 100.0))) if dmg else 0
        scatter = str(subdef.get("Scatter") or pdef.get("Scatter") or "")
        # rolling projectiles (logs / barrels) pierce everything on the path
        pierce = ("Rolling" in subp) or bool(subdef.get("Pierce"))
        if ang is None:
            ang = math.pi / 2.0 if team == 0 else -math.pi / 2.0
        for i in range(n):
            if n > 1 and scatter == "Circle":
                a = ang + i * 2.0 * math.pi / n
            elif n > 1 and scatter == "Line":
                a = ang + (i - (n - 1) / 2.0) * 0.18
            elif n > 1:
                a = ang + (i - (n - 1) / 2.0) * (math.pi / n)
            else:
                a = ang
            tx = x + math.cos(a) * rng_t
            ty = y + math.sin(a) * rng_t
            self.projectiles.append(Projectile(
                id=self._next_id, team=team, x=x, y=y, tx=tx, ty=ty,
                speed_t=speed, damage=dmg, tower_damage=tdm,
                splash_radius_t=radius,
                splash_air=bool(subdef.get("AoeToAir", True)),
                splash_ground=bool(subdef.get("AoeToGround", True)),
                pushback_t=_num(subdef.get("Pushback")) / 1000.0,
                spawn_character=subdef.get("SpawnCharacter") or "",
                spawn_count=int(subdef.get("SpawnCharacterCount") or 1),
                spawn_delay_ms=int(subdef.get("SpawnCharacterDeployTime")
                                   or 1000),
                name=subp, crown_pct=crown, max_range_t=rng_t,
                chain_depth=depth, pierce=pierce, angle=a,
                buff_name=subdef.get("TargetBuff") or "",
                buff_time_ms=int(subdef.get("BuffTime") or 0)))
            self._next_id += 1

    def _spawn_area_field(self, card: str, aeo: dict, team: int, x: float,
                          y: float, level_bonus: int = 0):
        radius = _num(aeo.get("Radius") or 0) / 1000.0
        life = int(aeo.get("LifeDuration") or 0)
        if not life:
            life = int(aeo.get("DurationSeconds") or 1) * 1000
        # instant AEOs carry LifeDuration 0/1 (Zap); keep them alive one tick
        life = max(TICK_MS + 50, life)
        dmg = aeo.get("Damage")
        tdmg = None
        if isinstance(dmg, dict):
            tdmg = dmg.get("TowerDamage")
            dmg = dmg.get("BaseDamage", 0)
        lvl = self.card_level + level_bonus
        dmg = _growth(int(dmg or 0), lvl, self.card_dmg_pct) if dmg else 0
        crown_pct = _num(aeo.get("CrownTowerDamagePercent"))
        tdmg_v = _growth(int(tdmg), lvl, self.card_dmg_pct) if tdmg else (
            max(1, int(dmg * (1 + crown_pct / 100.0))) if dmg else -1)
        hit_speed = int(aeo.get("HitSpeed") or 0)
        if hit_speed <= 0:
            hit_speed = int(aeo.get("HitSpeedOffset") or 0) or max(50, life)
        f = AreaField(
            id=self._next_id, team=team, name=aeo.get("Name") or card,
            x=x, y=y, radius_t=radius, until_ms=self.t + max(1, life),
            hit_speed_ms=max(50, hit_speed), tick_ms=0,
            damage=dmg, tower_damage=tdmg_v,
            crown_pct=crown_pct, level_bonus=level_bonus,
            started_ms=self.t)
        self._next_id += 1
        # characters released when the field expires (skeleton balloon barrels)
        soe = aeo.get("SpawnOnEnd")
        if isinstance(soe, dict) and isinstance(soe.get("Character"), str):
            f.spawn_on_end = [soe["Character"]] * max(1, int(soe.get("Count") or 1))
            f.spawn_on_end_radius_t = float(soe.get("Radius") or 0.0)
            f.spawn_on_end_delay_ms = int(soe.get("DeployTime") or 500)
        # buffs: single `Buff` or a `Buffs` list (Vines / GoblinCurse / DarkMagic)
        buffs: list[str] = []
        b0 = aeo.get("Buff")
        if isinstance(b0, str) and b0:
            buffs.append(b0)
        for b in aeo.get("Buffs") or []:
            if isinstance(b, str) and b not in buffs:
                buffs.append(b)
        if len(buffs) > 1:
            buffs = _pick_buff_variants(buffs)
        f.buff_names = buffs
        if buffs:
            f.buff_name = buffs[0]
            f.buff_time_ms = int(aeo.get("BuffTime") or 0)
            bd = self._buff_def(buffs[0])
            f.buff_ignore_buildings = bool(bd.get("IgnoreBuildings"))
            f.buff_no_crown = bool(bd.get("NoEffectToCrownTowers"))
            # friendly-filtered auras (Rage / Heal)
            filt = str(aeo.get("Filter") or "")
            low = filt.lower()
            if low.startswith("all_friendly") or low.startswith("friendly"):
                f.friendly_filter = True
            if "troop" in low or "character" in low:
                f.buff_troops_only = True
            if bd.get("DamagePerSecond") or bd.get("HealPerSecond"):
                f.hit_speed_ms = max(50, int(bd.get("HitFrequency")
                                             or f.hit_speed_ms))
            # crown damage reduction sometimes lives on the buff (Earthquake)
            bpct = bd.get("CrownTowerDamagePercent")
            if isinstance(bpct, (int, float)) and not crown_pct:
                f.crown_pct = float(bpct)
                if f.damage:
                    f.tower_damage = max(1, int(f.damage * (1 + bpct / 100.0)))
        # troop-only damage/buff (Earthquake)
        if aeo.get("BuffTroopsOnly"):
            f.buff_troops_only = True
            f.damage_buildings_only = bool(dmg)
        if aeo.get("DamageBuildingsOnly"):
            f.damage_buildings_only = True
        # delayed sub-AEOs (evolution Zap double strike, ...)
        for sub in aeo.get("SubAeos") or []:
            if isinstance(sub, dict) and sub.get("AEO"):
                f.sub_aeo_schedule.append((int(sub.get("t") or 0),
                                           sub["AEO"]))
        # spawn schedule (Graveyard)
        sched = aeo.get("SpawnSchedule")
        if isinstance(sched, list) and sched:
            f.spawn_schedule = [(int(e.get("t") or 0), e.get("Character"))
                                for e in sched if isinstance(e, dict)]
            f.spawn_limit_total = int(aeo.get("SpawnLimit")
                                      or len(f.spawn_schedule))
            # spawn locations are randomised within the field radius
        elif aeo.get("SpawnCharacter"):
            f.spawn_character = aeo["SpawnCharacter"]
            f.spawn_interval_ms = int(aeo.get("SpawnInterval") or 500)
            f.spawn_timer_ms = int(aeo.get("SpawnInitialDelay") or 2000)
            f.spawn_count = int(aeo.get("SpawnNumber") or 1)
        if aeo.get("SpawnMinRadius"):
            f.spawn_radius_min_t = _num(aeo.get("SpawnMinRadius")) / 1000.0
        # clone spell
        if aeo.get("Clone"):
            f.clone = True
        # target caps also apply to buff-only fields (Vines snare)
        f.max_targets = int(aeo.get("MaximumTargets") or 0)
        f.hit_biggest = bool(aeo.get("HitBiggestTargets"))
        f.one_hit_per_target = bool(aeo.get("OneHitPerTarget"))
        # field projectile (Lightning strikes / Royal Delivery barrel)
        proj = aeo.get("Projectile")
        if isinstance(proj, str) and proj:
            f.projectile_name = proj
            f.projectile_timer_ms = 0
        # sub-AEO (Rage deals its RageDamage)
        sub = aeo.get("SpawnAreaEffectObject")
        if isinstance(sub, str):
            f.sub_aeo = sub
        # tornado pull
        if f.buff_name == "Tornado":
            f.pull = 4.0
        if not (dmg or f.buff_name or f.spawn_character or f.spawn_schedule
                or f.clone or f.projectile_name or f.sub_aeo or f.heal
                or f.pull):
            return
        self.fields.append(f)
        # instant one-tick fields still need to act immediately
        f.tick_ms = 0
        if f.sub_aeo:
            ae = self.aeo.get(f.sub_aeo)
            if ae:
                self._spawn_area_field(f.sub_aeo, ae, team, x, y,
                                       level_bonus=level_bonus)
                f.sub_aeo_fired = True

    def _cast_spell(self, cm: dict, team: int, x: float, y: float,
                    level_bonus: int = 0):
        # AEO-based spells (Zap/Freeze/Poison/Graveyard/Tornado/Earthquake/
        # Lightning/RoyalDelivery/Rage/...)
        aeo = self.aeo.get(cm.get("AreaEffectObject") or "") or {}
        if aeo:
            self._spawn_area_field(cm.get("Name") or "", aeo, team, x, y,
                                   level_bonus=level_bonus)
            return
        # summon-char spell like Rage (bottle): apply its death AEO instantly
        summon = cm.get("SummonCharacter") or ""
        sdef = (self.model.get("characters", {}).get(summon)
                or self.model.get("buildings", {}).get(summon) or {})
        if sdef.get("DeathAreaEffect"):
            dae = self.aeo.get(sdef["DeathAreaEffect"]) or {}
            if dae:
                self._spawn_area_field(cm.get("Name") or summon, dae, team,
                                       x, y, level_bonus=level_bonus)
                return
        pdef = self.model.get("projectiles", {}).get(cm.get("Projectile") or "")
        if pdef:
            waves = int(cm.get("ProjectileWaves") or 1)
            if waves > 1:
                # multi-wave spell (Arrows): repeated hits over a short window
                lvl = self.card_level + level_bonus
                dmg = pdef.get("Damage")
                if isinstance(dmg, dict):
                    dmg = dmg.get("BaseDamage", 0)
                dmg = _growth(int(dmg or 0), lvl, self.card_dmg_pct)
                crown = _num(pdef.get("CrownTowerDamagePercent"))
                tdmg = max(1, int(dmg * (1 + crown / 100.0))) if dmg else -1
                radius = _num(cm.get("Radius") or pdef.get("Radius")) / 1000.0
                # 100ms simulation ticks mean a 250ms cadence lands on 300ms
                # boundaries; keep the field alive long enough for every wave.
                f = AreaField(
                    id=self._next_id, team=team, name=cm.get("Name") or "",
                    x=x, y=y, radius_t=radius,
                    until_ms=self.t + waves * (TICK_MS + 250) + 50,
                    hit_speed_ms=250, tick_ms=0, damage=dmg,
                    tower_damage=tdmg, crown_pct=crown,
                    level_bonus=level_bonus, started_ms=self.t)
                self._next_id += 1
                self.fields.append(f)
                return
            self._spell_projectile_damage(pdef, team, x, y,
                                          level_bonus=level_bonus, cm=cm)
            return
        # generic instantaneous damage field (InstantDamage + Radius)
        radius = _num(cm.get("Radius")) / 1000.0
        dmg = cm.get("InstantDamage")
        lvl = self.card_level + level_bonus
        if isinstance(dmg, int) and radius > 0:
            dmg = _growth(dmg, lvl, self.card_dmg_pct)
            for u in list(self.units):
                if u.team != team and u.hp > 0 and \
                        math.hypot(u.x - x, u.y - y) <= radius:
                    self._damage(u, dmg)
        heal = cm.get("InstantHeal")
        if isinstance(heal, int) and radius > 0:
            heal = _growth(heal, lvl, self.card_hp_pct)
            for u in self.units:
                if u.team == team and u.hp > 0 and \
                        math.hypot(u.x - x, u.y - y) <= radius:
                    u.hp = min(u.maxhp, u.hp + heal)
        hps = cm.get("HealPerSecond")
        dur = cm.get("DurationSeconds")
        if isinstance(hps, (int, float)) and radius > 0:
            ms = int((dur or 1) * 1000)
            heal = _growth(int(hps * 1000 / max(50, 500)), lvl, self.card_hp_pct)
            f = AreaField(id=self._next_id, team=team,
                          name=cm.get("Name") or "", x=x, y=y,
                          radius_t=radius, until_ms=self.t + ms,
                          hit_speed_ms=500, tick_ms=0, heal=heal,
                          friendly_filter=True, level_bonus=level_bonus,
                          started_ms=self.t)
            self._next_id += 1
            self.fields.append(f)

    # ------------------------------------------------------------- combat
    def _buff_effect_from_def(self, name: str, team: int = -1) -> BuffInst:
        d = self._buff_def(name)
        speed = d.get("SpeedMultiplier")
        hrate = d.get("HitSpeedMultiplier")
        stun = (speed is not None and speed <= -100) or \
               (hrate is not None and hrate <= -100)

        def multiplier(value):
            if not isinstance(value, (int, float)):
                return 1.0
            # Positive table values are percentages of the base stat (130 =
            # 1.30x); negative values are percentage reductions (-30 = 0.70x).
            if value <= -100:
                return 0.0
            return value / 100.0 if value >= 0 else 1.0 + value / 100.0

        dps = float(d.get("DamagePerSecond") or 0)
        heal = float(d.get("HealPerSecond") or 0)
        return BuffInst(
            name=name, until_ms=0, team=team,
            speed_mult=multiplier(speed),
            hitrate_mult=multiplier(hrate),
            dps=(_growth(dps, self.card_level, self.card_dmg_pct) if dps else 0.0),
            dps_hit_ms=max(50, int(d.get("HitFrequency") or 1000)),
            stun=stun, frozen=stun,
            heal_per_s=(_growth(heal, self.card_level, self.card_hp_pct)
                        if heal else 0.0),
            heal_hit_ms=max(50, int(d.get("HitFrequency") or 1000)),
            damage_reduction=_num(d.get("DamageReduction")) / 100.0,
            building_damage_pct=_num(d.get("BuildingDamagePercent")),
            crown_pct=_num(d.get("CrownTowerDamagePercent")),
            death_spawn=d.get("DeathSpawn") or "",
            death_spawn_count=int(d.get("DeathSpawnCount") or 1),
            death_spawn_enemy=bool(d.get("DeathSpawnIsEnemy")),
            invisible=bool(d.get("Invisible")),
            remove_on_attack=bool(d.get("RemoveOnAttack")),
            no_effect_crown=bool(d.get("NoEffectToCrownTowers")),
            ignore_buildings=bool(d.get("IgnoreBuildings")),
            clearance=bool(d.get("Clearance")))

    def _apply_buff(self, u: Unit, name: str, ms: int, team: int = -1):
        if not name or u.hp <= 0:
            return
        old = u.buffs.get(name)
        if old is not None and old.team == team:
            # refresh duration without resetting DoT/heal tick timers
            old.until_ms = max(old.until_ms, self.t + max(50, ms))
            return
        b = self._buff_effect_from_def(name, team)
        b.until_ms = self.t + max(50, ms)
        b.dps_timer_ms = b.dps_hit_ms
        b.heal_timer_ms = b.heal_hit_ms
        u.buffs[name] = b
        if b.invisible:
            u.invisible = True

    def _speed_mult(self, u: Unit) -> float:
        m = 1.0
        for b in u.buffs.values():
            if b.stun:
                return 0.0
            m *= b.speed_mult
        return m

    def _hitrate_mult(self, u: Unit) -> float:
        m = 1.0
        for b in u.buffs.values():
            if b.stun:
                return 0.0
            m *= b.hitrate_mult
        return max(0.0, m)

    def _damage(self, u: Unit, dmg: int, source: Unit | None = None):
        if dmg <= 0 or u.hp <= 0:
            return
        # percentage damage reduction buffs (Knight evolution fortify ...)
        red = sum(b.damage_reduction for b in u.buffs.values())
        if red > 0:
            dmg = max(1, int(dmg * max(0.2, 1.0 - red)))
        if isinstance(u, Tower) and u.kind == "KingTower" and not u.activated:
            u.activated = True
            u.atk_cd_ms = u.load_ms
        if u.shield_hp > 0:
            absorbed = min(u.shield_hp, dmg)
            u.shield_hp -= absorbed
            dmg -= absorbed
        u.hp -= dmg
        if u.hp <= 0:
            self._on_death(u)

    def _pushback_from(self, x: float, y: float, radius: float, amount: float,
                       team: int):
        for u in self.units:
            if u.team == team or u.hp <= 0 or u.ignore_pushback \
                    or isinstance(u, Tower) or u.is_building:
                continue
            d = math.hypot(u.x - x, u.y - y)
            if d > radius or d < 1e-6:
                continue
            u.x = min(ARENA_W, max(0.0, u.x + (u.x - x) / d * amount))
            u.y = min(ARENA_H, max(0.0, u.y + (u.y - y) / d * amount))

    def _on_death(self, u: Unit):
        if isinstance(u, Tower):
            self.crowns[1 - u.team] += 1
            self.events.append((self.t, f"{u.kind} down ({u.team})"))
            if u.kind == "PrincessTower":
                for k in self.units:
                    if (isinstance(k, Tower) and k.kind == "KingTower"
                            and k.team == u.team and k.hp > 0
                            and not k.activated):
                        k.activated = True
            else:
                self.crowns[1 - u.team] = 3
            return
        if u.death_area_effect:
            dae = self.aeo.get(u.death_area_effect) or {}
            if dae:
                self._spawn_area_field(u.death_area_effect, dae, u.team,
                                       u.x, u.y)
        for da in u.death_aeos or []:
            an = da.get("AEO") if isinstance(da, dict) else ""
            dae = self.aeo.get(an) if an else None
            if dae:
                self._spawn_area_field(an, dae, u.team,
                                       u.x + float(da.get("DX") or 0.0),
                                       u.y + float(da.get("DY") or 0.0))
        # buff-carried death spawns (Goblin Curse transforms the victim)
        if not (u.is_building and not isinstance(u, Tower)):
            for b in list(u.buffs.values()):
                if not b.death_spawn:
                    continue
                spawner = (b.team if b.team in (0, 1)
                           else (1 - u.team if b.death_spawn_enemy else u.team))
                for i in range(max(1, b.death_spawn_count)):
                    self._place(b.death_spawn, spawner,
                                u.x + (i - (b.death_spawn_count - 1) / 2.0) * 0.5,
                                u.y)
        spawn_pairs = []
        if u.death_spawn_character:
            spawn_pairs.append((u.death_spawn_character, max(1, u.death_spawn_count)))
        if u.death_spawn_2:
            spawn_pairs.append((u.death_spawn_2, max(1, u.death_spawn_2_count)))
        # Ram: rider spawns from SpawnCharacter list on death
        if not spawn_pairs and u.spawn_character and u.spawn_number and not u.is_building:
            spawn_pairs.append((u.spawn_character, u.spawn_number))
        for cname, count in spawn_pairs:
            for i in range(count):
                self._place(cname, u.team,
                            u.x + (i - (count - 1) / 2.0) * 0.5, u.y)

    def _valid(self, a: Unit, b: Unit) -> bool:
        if b.hp <= 0 or b.team == a.team:
            return False
        if b.invisible:
            # invisible units cannot be targeted until they attack
            return False
        if b.flying and not a.attacks_air:
            return False
        if not b.flying and not a.attacks_ground:
            return False
        if a.target_only_buildings and not (b.is_building or isinstance(b, Tower)):
            return False
        return True

    def _splash(self, attacker: Unit, tx: float, ty: float, radius: float,
                primary: Unit | None, dmg: int, tower_dmg: int):
        air_ok, ground_ok = attacker.splash_air, attacker.splash_ground
        for b in list(self.units):
            if not self._valid(attacker, b):
                continue
            if b is not primary:
                if b.flying and not air_ok:
                    continue
                if not b.flying and not ground_ok:
                    continue
            if math.hypot(b.x - tx, b.y - ty) > radius + b.col_t:
                continue
            d = tower_dmg if isinstance(b, Tower) and tower_dmg else dmg
            self._damage(b, d)

    def _attack(self, a: Unit, target: Unit):
        """Perform one attack (melee instant or projectile launch)."""
        for k in [k for k, b in a.buffs.items() if b.remove_on_attack]:
            a.buffs.pop(k, None)
        a.invisible = any(b.invisible for b in a.buffs.values())
        dmg = a.damage
        tower_dmg = a.tower_damage
        if a.charged:
            a.charged = False
            a.charge_dist = 0.0
            dmg = int(dmg * CHARGED_DAMAGE_MULT)
            tower_dmg = int(tower_dmg * CHARGED_DAMAGE_MULT) if tower_dmg else 0
        if a.ramp_values and a.ramp_stage > 0:
            idx = min(a.ramp_stage - 1, len(a.ramp_values) - 1)
            dmg = a.ramp_values[idx]
        if a.projectile_name and a.projectile_speed_t > 0:
            self._launch_projectile(a, target, dmg, tower_dmg)
        else:
            self._damage(target, tower_dmg if isinstance(target, Tower) and tower_dmg else dmg)
            if a.splash_radius_t > 0:
                self._splash(a, target.x, target.y, a.splash_radius_t, target,
                             dmg, tower_dmg)
            if a.attack_pushback_t and not target.ignore_pushback \
                    and not isinstance(target, Tower):
                self._knock(target, a)
        a.atk_cd_ms = int(a.hit_speed_ms / max(0.01, self._hitrate_mult(a)))
        a.atk_count += 1
        if a.kamikaze:
            a.hp = 0
            self._on_death(a)

    def _knock(self, target: Unit, attacker: Unit):
        d = math.hypot(target.x - attacker.x, target.y - attacker.y)
        if d < 1e-6:
            return
        k = attacker.attack_pushback_t
        target.x = min(ARENA_W, max(0.0, target.x + (target.x - attacker.x) / d * k))
        target.y = min(ARENA_H, max(0.0, target.y + (target.y - attacker.y) / d * k))

    def _launch_projectile(self, a: Unit, target: Unit, dmg: int, tower_dmg: int):
        ang = math.atan2(target.y - a.y, target.x - a.x)
        pdef = self.model.get("projectiles", {}).get(a.projectile_name or "") or {}
        self.projectiles.append(Projectile(
            id=self._next_id, team=a.team, x=a.x, y=a.y,
            tx=target.x, ty=target.y, speed_t=a.projectile_speed_t,
            damage=dmg, tower_damage=tower_dmg,
            splash_radius_t=a.splash_radius_t,
            splash_air=a.splash_air, splash_ground=a.splash_ground,
            homing_target_id=target.id if a.projectile_homing else -1,
            pushback_t=a.attack_pushback_t,
            name=a.projectile_name, angle=ang,
            source_id=a.id,
            return_on_impact=bool(pdef.get("PingpongVisualTime")),
            strong_damage=a.strong_damage,
            strong_range_t=a.strong_range_t,
            strong_pushback_t=a.strong_pushback_t))
        self._next_id += 1

    # ------------------------------------------------------------ targeting
    def _pick(self, u: Unit, can_default_goal: bool = True) -> Unit | None:
        reach = max(u.range_t, u.sight_t if not (u.is_building or isinstance(u, Tower)) else u.range_t)
        best, bd = None, 1e9
        for b in self.units:
            if not self._valid(u, b):
                continue
            d = math.hypot(b.x - u.x, b.y - u.y) - (u.col_t + b.col_t)
            if u.min_range_t > 0 and d < u.min_range_t - 0.01:
                continue
            if d < bd and d <= reach:
                best, bd = b, d
        if best:
            return best
        if can_default_goal and not isinstance(u, Tower):
            # march toward the nearest enemy tower (keeps troops advancing)
            towers = [b for b in self.units if isinstance(b, Tower)
                      and b.team != u.team and b.hp > 0]
            if towers:
                return min(towers, key=lambda b: math.hypot(b.x - u.x, b.y - u.y))
        return None

    # ------------------------------------------------------------ movement
    def _bridge_for(self, u: Unit) -> float:
        return min(BRIDGES_X, key=lambda bx: abs(bx - u.x))

    def _waypoint(self, u: Unit, tx: float, ty: float):
        if u.flying or u.jump_enabled:
            return tx, ty

        bridge = self._bridge_for(u)
        y_blue_bank = RIVER_Y - RIVER_HALF - 0.4  # 15.0
        y_red_bank = RIVER_Y + RIVER_HALF + 0.4   # 17.0

        # If target is already on the bridge corridor with unit, walk directly to it
        if abs(tx - bridge) <= 0.6 and y_blue_bank <= ty <= y_red_bank:
            return tx, ty

        # Hysteresis corridor lock: while unit is in the river crossing corridor [15.0, 17.0]
        # Keep x-locked to bridge and advance straight through to the exit threshold
        if y_blue_bank <= u.y <= y_red_bank:
            if ty < RIVER_Y:
                return bridge, y_blue_bank - 0.2
            else:
                return bridge, y_red_bank + 0.2

        # Approaching river crossing from either bank
        if (u.y - RIVER_Y) * (ty - RIVER_Y) < 0:
            if u.y < RIVER_Y:
                # Blue side -> Red side (+y direction)
                if abs(u.x - bridge) > 0.35:
                    return bridge, y_blue_bank
                else:
                    return bridge, y_red_bank + 0.2
            else:
                # Red side -> Blue side (-y direction)
                if abs(u.x - bridge) > 0.35:
                    return bridge, y_red_bank
                else:
                    return bridge, y_blue_bank - 0.2

        return tx, ty

    # ------------------------------------------------------------ lifecycle
    def step(self, actions=None):
        if self.done:
            return
        self.t += TICK_MS
        bar_ms = self._bar_ms()
        for team in (0, 1):
            self.elixir[team] = min(MAX_ELIXIR,
                                    self.elixir[team] + 10.0 * TICK_MS / bar_ms)
            if self.play_cd[team] > 0:
                self.play_cd[team] = max(0, self.play_cd[team] - TICK_MS)

        for team, idx, x, y in (actions or []):
            if 0 <= team <= 1:
                self.play(team, int(idx), float(x), float(y))

        self._step_fields()
        self._step_units()
        self._step_projectiles()

        if any(u.hp <= 0 for u in self.units):
            self.units = [u for u in self.units if u.hp > 0]

        self._check_end()

    def _step_fields(self):
        for f in list(self.fields):
            if self.t >= f.until_ms:
                if f.spawn_on_end:
                    rad = f.spawn_on_end_radius_t or 1.0
                    for cname in f.spawn_on_end:
                        ang = self.rng.uniform(0.0, 2.0 * math.pi)
                        rr = self.rng.uniform(0.0, max(0.1, rad))
                        u = self._place(
                            cname, f.team,
                            min(ARENA_W, max(0.0, f.x + math.cos(ang) * rr)),
                            min(ARENA_H, max(0.0, f.y + math.sin(ang) * rr)),
                            level_bonus=f.level_bonus)
                        if u:
                            u.load_ms = f.spawn_on_end_delay_ms
                self.fields.remove(f)
                continue
            elapsed = self.t - f.started_ms
            # delayed sub-AEOs (evolved Zap double strike, ...)
            while (f.sub_aeo_made < len(f.sub_aeo_schedule)
                   and f.sub_aeo_schedule[f.sub_aeo_made][0] <= elapsed):
                _, aname = f.sub_aeo_schedule[f.sub_aeo_made]
                f.sub_aeo_made += 1
                ae = self.aeo.get(aname)
                if ae:
                    self._spawn_area_field(aname, ae, f.team, f.x, f.y,
                                           level_bonus=f.level_bonus)
            # scheduled character spawns (Graveyard)
            if f.spawn_schedule:
                while (f.spawn_made < len(f.spawn_schedule)
                       and f.spawn_schedule[f.spawn_made][0] <= elapsed
                       and (not f.spawn_limit_total
                            or f.spawn_made < f.spawn_limit_total)):
                    _, cname = f.spawn_schedule[f.spawn_made]
                    f.spawn_made += 1
                    if cname:
                        ang = self.rng.uniform(0.0, 2.0 * math.pi)
                        rr = self.rng.uniform(0.0, max(0.1, f.radius_t * 0.7))
                        u = self._place(
                            cname, f.team,
                            min(ARENA_W, max(0.0, f.x + math.cos(ang) * rr)),
                            min(ARENA_H, max(0.0, f.y + math.sin(ang) * rr)),
                            level_bonus=f.level_bonus)
                        if u:
                            u.load_ms = 500
            f.tick_ms -= TICK_MS
            if f.tick_ms > 0:
                continue
            f.tick_ms = max(50, f.hit_speed_ms)
            remaining = max(50, f.until_ms - self.t)
            # tornado pull
            if f.pull:
                for u in self.units:
                    if u.team == f.team or u.hp <= 0 \
                            or isinstance(u, Tower) or u.is_building:
                        continue
                    d = math.hypot(u.x - f.x, u.y - f.y)
                    if d <= f.radius_t and d > 0.15:
                        step = f.pull * f.hit_speed_ms / 1000.0
                        u.x += (f.x - u.x) / d * min(step, d)
                        u.y += (f.y - u.y) / d * min(step, d)
            # clone spell (single cast)
            if f.clone and not f.clone_done:
                f.clone_done = True
                self._clone_units(f)
            # buff application
            if f.buff_names:
                full = int(f.buff_time_ms or (f.hit_speed_ms + 100))
                span = max(1, f.until_ms - f.started_ms)
                if span <= 2 * TICK_MS:
                    # instant AEO (Zap): the debuff outlives the field
                    ms = max(50, full)
                else:
                    ms = int(min(max(full, 200), remaining + TICK_MS))
                ms = max(50, ms)
                if f.friendly_filter:
                    targets = [u for u in self.units
                               if u.hp > 0 and u.team == f.team
                               and not isinstance(u, Tower) and not u.is_building
                               and math.hypot(u.x - f.x, u.y - f.y) <= f.radius_t + u.col_t]
                else:
                    targets = [u for u in self.units
                               if u.hp > 0 and u.team != f.team
                               and math.hypot(u.x - f.x, u.y - f.y) <= f.radius_t + u.col_t]
                    if f.buff_troops_only:
                        targets = [u for u in targets
                                   if not (isinstance(u, Tower) or u.is_building)]
                    if f.buff_ignore_buildings:
                        targets = [u for u in targets
                                   if not (isinstance(u, Tower) or u.is_building)]
                    if f.buff_no_crown:
                        targets = [u for u in targets
                                   if not isinstance(u, Tower)]
                if f.one_hit_per_target:
                    targets = [u for u in targets if u.id not in f.hit_targets]
                if f.max_targets and len(targets) > f.max_targets:
                    if f.hit_biggest:
                        targets.sort(key=lambda u: -u.hp)
                    else:
                        targets.sort(key=lambda u: math.hypot(u.x - f.x,
                                                              u.y - f.y))
                    targets = targets[:f.max_targets]
                for u in targets:
                    f.hit_targets.add(u.id)
                    for bname in f.buff_names:
                        self._apply_buff(u, bname, ms, f.team)
            # damage ticks
            if f.damage:
                for u in list(self.units):
                    if u.team == f.team or u.hp <= 0:
                        continue
                    if math.hypot(u.x - f.x, u.y - f.y) > f.radius_t + u.col_t:
                        continue
                    if f.damage_buildings_only and not (
                            isinstance(u, Tower) or u.is_building):
                        continue
                    if isinstance(u, Tower):
                        if f.tower_damage >= 0:
                            self._damage(u, f.tower_damage)
                        else:
                            self._damage(u, max(1, int(
                                f.damage * (1 + f.crown_pct / 100))))
                    else:
                        self._damage(u, f.damage)
            # healing aura
            if f.heal:
                for u in self.units:
                    if (u.team == f.team and u.hp > 0
                            and not isinstance(u, Tower) and not u.is_building
                            and math.hypot(u.x - f.x, u.y - f.y) <= f.radius_t + u.col_t):
                        u.hp = min(u.maxhp, u.hp + f.heal)
            # field projectiles (Lightning strikes / Royal Delivery)
            if f.projectile_name:
                self._field_fire_projectile(f)

    def _clone_units(self, f: AreaField):
        for u in list(self.units):
            if (u.team != f.team or u.hp <= 0 or u.is_clone
                    or isinstance(u, Tower) or u.is_building):
                continue
            if math.hypot(u.x - f.x, u.y - f.y) > f.radius_t + u.col_t:
                continue
            c = replace(u, id=self._next_id, hp=1, maxhp=1, shield_hp=0,
                        is_clone=True, buffs={}, target_id=-1,
                        atk_cd_ms=0, load_ms=0, spawn_made=0,
                        spawn_timer_ms=0, mana_timer_ms=0,
                        ramp_timer_ms=0, ramp_stage=0)
            self._next_id += 1
            self.units.append(c)

    def _field_fire_projectile(self, f: AreaField):
        pdef = self.model.get("projectiles", {}).get(f.projectile_name) or {}
        if not pdef:
            return
        enemies = [u for u in self.units if u.hp > 0 and u.team != f.team
                   and math.hypot(u.x - f.x, u.y - f.y) <= f.radius_t + u.col_t]
        if f.one_hit_per_target:
            enemies = [u for u in enemies if u.id not in f.hit_targets]
        if not enemies:
            if not f.projectile_fired and pdef.get("SpawnCharacter"):
                f.projectile_fired = True
                self._launch_field_projectile(f, pdef, f.x, f.y, -1)
            return
        if f.hit_biggest:
            enemies.sort(key=lambda u: -u.hp)
        else:
            enemies.sort(key=lambda u: math.hypot(u.x - f.x, u.y - f.y))
        n = f.max_targets or 1
        for u in enemies[:n]:
            f.hit_targets.add(u.id)
            self._launch_field_projectile(f, pdef, u.x, u.y, u.id)
        f.projectile_fired = True

    def _launch_field_projectile(self, f: AreaField, pdef: dict,
                                 tx: float, ty: float, target_id: int):
        dmg = pdef.get("Damage")
        tdmg = pdef.get("TowerDamage")
        if isinstance(dmg, dict):
            tdmg = dmg.get("TowerDamage", tdmg)
            dmg = dmg.get("BaseDamage", 0)
        lvl = self.card_level + f.level_bonus
        dmg = _growth(int(dmg or 0), lvl, self.card_dmg_pct) if dmg else 0
        cpct = _num(pdef.get("CrownTowerDamagePercent", f.crown_pct))
        tdmg = _growth(int(tdmg), lvl, self.card_dmg_pct) if tdmg else (
            max(1, int(dmg * (1 + cpct / 100.0))) if dmg else 0)
        speed = max(3.0, _num(pdef.get("Speed")) * PROJECTILE_TILE_S_PER_UNIT)
        self.projectiles.append(Projectile(
            id=self._next_id, team=f.team,
            x=tx, y=max(0.2, ty - 2.5), tx=tx, ty=ty,
            speed_t=speed, damage=dmg, tower_damage=tdmg,
            splash_radius_t=_num(pdef.get("Radius")) / 1000.0,
            splash_air=bool(pdef.get("AoeToAir", True)),
            splash_ground=bool(pdef.get("AoeToGround", True)),
            homing_target_id=target_id,
            name=f.projectile_name, crown_pct=cpct,
            buff_name=pdef.get("TargetBuff") or "",
            buff_time_ms=int(pdef.get("BuffTime") or 0),
            spawn_character=pdef.get("SpawnCharacter") or "",
            spawn_count=int(pdef.get("SpawnCharacterCount") or 1),
            spawn_delay_ms=int(pdef.get("SpawnCharacterDeployTime") or 1000),
            max_range_t=99.0))
        self._next_id += 1

    def _step_hp_events(self, u: Unit) -> bool:
        """HP-threshold drops / relocations. Returns True while hidden."""
        if isinstance(u, Tower):
            return False
        if u.relocate_ms > 0:
            u.relocate_ms -= TICK_MS
            u.invisible = True
            if u.relocate_ms <= 0:
                u.invisible = any(b.invisible for b in u.buffs.values())
                # reappear closer to the enemy side, as the drill does
                ny = u.y + (2.2 if u.team == 0 else -2.2)
                u.y = min(ARENA_H, max(0.0, ny))
                an = (u.hp_relocate or {}).get("AEO")
                ae = self.aeo.get(an) if an else None
                if ae:
                    self._spawn_area_field(an, ae, u.team, u.x, u.y)
            return True
        if not u.hp_drops and not u.hp_relocate:
            return False
        frac = 100.0 * u.hp / max(1, u.maxhp)
        for i, hd in enumerate(u.hp_drops):
            if i in u.hp_drops_done:
                continue
            if frac <= float(hd.get("Pct") or 0):
                u.hp_drops_done.add(i)
                an = hd.get("AEO") or ""
                ae = self.aeo.get(an) if an else None
                if ae:
                    self._spawn_area_field(
                        an, ae, u.team,
                        u.x + float(hd.get("DX") or 0.0),
                        u.y + float(hd.get("DY") or 0.0))
        rel = u.hp_relocate
        for i, pct in enumerate((rel or {}).get("Thresholds") or []):
            if i in u.hp_relocate_done:
                continue
            if frac <= float(pct):
                u.hp_relocate_done.add(i)
                spawns = (rel or {}).get("Spawns") or []
                for cname in (spawns[i] if i < len(spawns) else []):
                    self._place(cname, u.team, u.x, u.y)
                an = (rel or {}).get("AEO")
                ae = self.aeo.get(an) if an else None
                if ae:
                    self._spawn_area_field(an, ae, u.team, u.x, u.y)
                u.relocate_ms = max(100, int((rel or {}).get("HideMs") or 1000))
                u.invisible = True
                return True
        return False

    def _step_units(self):
        # buff expiry, damage-over-time and healing-over-time
        for u in self.units:
            if not u.buffs:
                u.invisible = False
                continue
            expired = []
            for bname, b in list(u.buffs.items()):
                if b.dps > 0 and u.hp > 0:
                    b.dps_timer_ms -= TICK_MS
                    if b.dps_timer_ms <= 0:
                        b.dps_timer_ms += b.dps_hit_ms
                        if not (isinstance(u, Tower) and b.no_effect_crown):
                            amt = max(1, int(round(b.dps * b.dps_hit_ms / 1000.0)))
                            if isinstance(u, Tower):
                                amt = max(1, int(round(
                                    amt * max(0.05, 1 + b.crown_pct / 100.0))))
                            self._damage(u, amt)
                if b.heal_per_s > 0 and u.hp > 0 and not isinstance(u, Tower) \
                        and not u.is_building:
                    b.heal_timer_ms -= TICK_MS
                    if b.heal_timer_ms <= 0:
                        b.heal_timer_ms += b.heal_hit_ms
                        amt = int(round(b.heal_per_s * b.heal_hit_ms / 1000.0))
                        u.hp = min(u.maxhp, u.hp + amt)
                if self.t >= b.until_ms:
                    expired.append(bname)
            for bname in expired:
                u.buffs.pop(bname, None)
            u.invisible = any(b.invisible for b in u.buffs.values())

        for u in self.units:
            if u.hp <= 0:
                continue
            if self._step_hp_events(u):
                continue
            if u.load_ms > 0:
                u.load_ms -= TICK_MS
                continue
            # passive buff while not attacking (Knight fortify / Ghost invis)
            if u.passive_buff:
                if u.atk_cd_ms <= 0:
                    self._apply_buff(u, u.passive_buff, u.passive_buff_ms, u.team)
                elif any(b.remove_on_attack for b in u.buffs.values()):
                    for k in [k for k, b in u.buffs.items() if b.remove_on_attack]:
                        u.buffs.pop(k, None)
                    u.invisible = False
            # buildings: lifetime, spawning, elixir production
            if u.is_building or isinstance(u, Tower):
                if u.lifetime_ms > 0:
                    u.lifetime_ms -= TICK_MS
                    if u.lifetime_ms <= 0:
                        u.hp = 0
                        self._on_death(u)
                        continue
                if u.mana_collect and u.mana_interval_ms:
                    u.mana_timer_ms -= TICK_MS
                    if u.mana_timer_ms <= 0:
                        u.mana_timer_ms = u.mana_interval_ms
                        self.elixir[u.team] = min(MAX_ELIXIR,
                                                  self.elixir[u.team] + u.mana_collect)
                if u.spawn_number and u.spawn_pause_ms:
                    u.spawn_timer_ms -= TICK_MS
                    if u.spawn_timer_ms <= 0:
                        u.spawn_timer_ms = u.spawn_pause_ms
                        alive = sum(1 for b in self.units
                                    if b.name == u.spawn_character and b.team == u.team)
                        if not u.spawn_limit or alive < u.spawn_limit:
                            for i in range(u.spawn_number):
                                self._place(u.spawn_character, u.team,
                                            u.x + (i - (u.spawn_number - 1) / 2.0) * 0.6,
                                            u.y + 0.8)
            # attack cooldown
            if u.atk_cd_ms > 0:
                u.atk_cd_ms -= TICK_MS

            if isinstance(u, Tower):
                if u.kind == "KingTower" and not u.activated:
                    continue
                self._tower_brain(u)
                continue
            if u.is_building:
                self._tower_brain(u)   # buildings attack like towers
                continue

            # troop brain ---------------------------------------------------
            if self._speed_mult(u) <= 0.0:
                continue
            tgt = next((b for b in self.units
                        if b.id == u.target_id and b.hp > 0 and self._valid(u, b)),
                       None)
            if tgt is None or u.ramp_timer_ms == 0:
                new_t = self._pick(u)
                if new_t is not None and (tgt is None or new_t.id != tgt.id):
                    u.ramp_timer_ms = 0
                    u.ramp_stage = 0
                if new_t is not None:
                    tgt = new_t
                    u.target_id = tgt.id
            if tgt is None:
                continue
            d_edge = math.hypot(tgt.x - u.x, tgt.y - u.y) - (u.col_t + tgt.col_t)

            # Bandit-style dash
            if u.dash_max_range_t and u.dash_cd_ms <= 0 and d_edge > u.range_t \
                    and d_edge <= u.dash_max_range_t:
                self._do_dash(u, tgt)
                continue

            if d_edge <= u.range_t and (u.min_range_t <= 0
                                        or d_edge >= u.min_range_t - 0.01):
                if u.atk_cd_ms <= 0:
                    self._attack(u, tgt)
                # ramp bookkeeping (inferno): only while actively hitting
                if u.ramp_values:
                    u.ramp_timer_ms += TICK_MS
                    stage = 0
                    acc = 0
                    for i, tm in enumerate(u.ramp_times):
                        acc += tm
                        if u.ramp_timer_ms >= acc:
                            stage = i + 1
                    u.ramp_stage = stage
            else:
                # move toward target (charge state machine)
                wx, wy = self._waypoint(u, tgt.x, tgt.y)
                dx, dy = wx - u.x, wy - u.y
                dist = math.hypot(dx, dy) or 1.0
                spd = u.speed_t * self._speed_mult(u)
                if u.charge_range_t and u.charged:
                    spd *= u.charge_speed_mult
                move = min(spd * TICK_MS / 1000.0, dist)
                u.x += dx / dist * move
                u.y += dy / dist * move
                if u.charge_range_t:
                    u.charge_dist += move
                    if not u.charged and u.charge_dist >= u.charge_range_t:
                        u.charged = True
                if u.ramp_timer_ms:
                    u.ramp_timer_ms = 0
                    u.ramp_stage = 0
            if u.dash_cd_ms > 0:
                u.dash_cd_ms -= TICK_MS

    def _do_dash(self, u: Unit, tgt: Unit):
        d = math.hypot(tgt.x - u.x, tgt.y - u.y)
        if d > 1e-6:
            u.x = tgt.x - (tgt.x - u.x) / d * (u.range_t + u.col_t)
            u.y = tgt.y - (tgt.y - u.y) / d * (u.range_t + u.col_t)
        if u.dash_damage:
            self._damage(tgt, u.dash_damage)
        if u.splash_radius_t:
            self._splash(u, tgt.x, tgt.y, u.splash_radius_t, tgt,
                         u.damage, u.tower_damage)
        u.dash_cd_ms = u.dash_cooldown_ms or 5000
        u.atk_cd_ms = u.hit_speed_ms
        if u.kamikaze:
            u.hp = 0
            self._on_death(u)

    def _tower_brain(self, u: Unit):
        tgt = next((b for b in self.units
                    if b.id == u.target_id and b.hp > 0 and self._valid(u, b)
                    and math.hypot(b.x - u.x, b.y - u.y) - (u.col_t + b.col_t) <= u.range_t),
                   None)
        if tgt is None:
            best, bd = None, 1e9
            for b in self.units:
                if not self._valid(u, b):
                    continue
                d = math.hypot(b.x - u.x, b.y - u.y) - (u.col_t + b.col_t)
                if d <= u.range_t and d < bd:
                    best, bd = b, d
            tgt = best
            u.target_id = tgt.id if tgt else -1
        if tgt and u.atk_cd_ms <= 0:
            self._attack(u, tgt)

    def _step_projectiles(self):
        for p in list(self.projectiles):
            if p.homing_target_id >= 0:
                tgt = next((b for b in self.units
                            if b.id == p.homing_target_id and b.hp > 0), None)
                if tgt:
                    p.tx, p.ty = tgt.x, tgt.y
            dx, dy = p.tx - p.x, p.ty - p.y
            dist = math.hypot(dx, dy)
            move = p.speed_t * TICK_MS / 1000.0
            if p.pierce:
                step = min(move, dist)
                nx, ny = (p.x, p.y) if dist < 1e-6 else (
                    p.x + dx / dist * step, p.y + dy / dist * step)
                for u in self.units:
                    if u.team == p.team or u.hp <= 0 or u.id in p.hit_ids:
                        continue
                    if p.buildings_only and not (u.is_building
                                                 or isinstance(u, Tower)):
                        continue
                    if _seg_dist(p.x, p.y, nx, ny, u.x, u.y) <= (p.splash_radius_t or 0.5) + u.col_t:
                        p.hit_ids.add(u.id)
                        self._damage(u, p.tower_damage
                                     if isinstance(u, Tower) and p.tower_damage
                                     else p.damage)
                        if p.buff_name:
                            self._apply_buff(u, p.buff_name,
                                             p.buff_time_ms or 1000, p.team)
                        if p.pushback_t and not isinstance(u, Tower) \
                                and not u.ignore_pushback:
                            d2 = math.hypot(u.x - nx, u.y - ny) or 1.0
                            u.x = min(ARENA_W, max(0.0, u.x + (u.x - nx) / d2
                                                  * p.pushback_t))
                            u.y = min(ARENA_H, max(0.0, u.y + (u.y - ny) / d2
                                                  * p.pushback_t))
                p.x, p.y = nx, ny
                p.travelled_t += step
                if p.travelled_t >= p.max_range_t or dist <= max(move, 0.05):
                    self._impact(p)
                    self.projectiles.remove(p)
            elif dist <= max(move, 0.05):
                self._impact(p)
                self.projectiles.remove(p)
            else:
                p.x += dx / dist * move
                p.y += dy / dist * move

    def _impact(self, p: Projectile):
        victims = [b for b in self.units if b.hp > 0 and b.team != p.team]
        if p.pierce and p.hit_ids:
            victims = [b for b in victims if b.id not in p.hit_ids]
        if p.splash_radius_t > 0:
            hits = [b for b in victims
                    if math.hypot(b.x - p.tx, b.y - p.ty) <= p.splash_radius_t + b.col_t
                    and ((b.flying and p.splash_air) or (not b.flying and p.splash_ground))]
        else:
            hits = [b for b in victims
                    if math.hypot(b.x - p.x, b.y - p.y) <= 0.35 + b.col_t]
            if not hits:
                hits = [b for b in victims
                        if math.hypot(b.x - p.tx, b.y - p.ty) <= 0.4 + b.col_t]
        src = next((u for u in self.units
                    if u.id == p.source_id and u.hp > 0), None)
        for b in hits:
            if p.buildings_only and not (b.is_building or isinstance(b, Tower)):
                continue
            dmg = (p.tower_damage if isinstance(b, Tower) and p.tower_damage
                   else p.damage)
            strong = False
            if p.strong_damage and src is not None and math.hypot(
                    b.x - src.x, b.y - src.y) <= p.strong_range_t + b.col_t:
                dmg = p.strong_damage
                strong = True
            self._damage(b, dmg)
            if p.buff_name:
                self._apply_buff(b, p.buff_name, p.buff_time_ms or 1000, p.team)
            if p.pushback_t and not isinstance(b, Tower) and not b.ignore_pushback:
                bx, by = p.x, p.y
                d = math.hypot(b.x - bx, b.y - by) or 1.0
                b.x = min(ARENA_W, max(0.0, b.x + (b.x - bx) / d * p.pushback_t))
                b.y = min(ARENA_H, max(0.0, b.y + (b.y - by) / d * p.pushback_t))
            if strong and p.strong_pushback_t and not isinstance(b, Tower) \
                    and not b.ignore_pushback and src is not None:
                d = math.hypot(b.x - src.x, b.y - src.y) or 1.0
                b.x = min(ARENA_W, max(0.0, b.x + (b.x - src.x) / d
                                       * p.strong_pushback_t))
                b.y = min(ARENA_H, max(0.0, b.y + (b.y - src.y) / d
                                       * p.strong_pushback_t))
        # executioner axes return to the thrower for a second pass
        if p.return_on_impact and src is not None:
            self.projectiles.append(Projectile(
                id=self._next_id, team=p.team, x=p.tx, y=p.ty,
                tx=src.x, ty=src.y, speed_t=p.speed_t, damage=p.damage,
                tower_damage=p.tower_damage,
                splash_radius_t=p.splash_radius_t,
                splash_air=p.splash_air, splash_ground=p.splash_ground,
                homing_target_id=src.id, pierce=True, max_range_t=99.0,
                pushback_t=p.pushback_t, name="", source_id=p.source_id,
                strong_damage=p.strong_damage, strong_range_t=p.strong_range_t,
                strong_pushback_t=p.strong_pushback_t))
            self._next_id += 1
        # payload carried by the projectile definition
        pdef = self.model.get("projectiles", {}).get(p.name or "") or {}
        if pdef and p.chain_depth < 3:
            buff = pdef.get("TargetBuff") or ""
            btime = int(pdef.get("BuffTime") or 0)
            if buff:
                for b in hits:
                    self._apply_buff(b, buff, btime or 1000, p.team)
            cnt = int(pdef.get("ChainedHitCount") or 0)
            if cnt > 0:
                chain_r = _num(pdef.get("ChainedHitRadius")) / 1000.0
                cdmg = pdef.get("Damage")
                if isinstance(cdmg, dict):
                    cdmg = cdmg.get("BaseDamage", 0)
                seen = {b.id for b in hits}
                pool = sorted((u for u in self.units
                               if u.hp > 0 and u.team != p.team
                               and u.id not in seen
                               and math.hypot(u.x - p.tx, u.y - p.ty)
                               <= chain_r + u.col_t),
                              key=lambda u: math.hypot(u.x - p.tx, u.y - p.ty))
                for u in pool[:cnt]:
                    if isinstance(cdmg, (int, float)) and cdmg > 0:
                        self._damage(u, _growth(int(cdmg), self.card_level,
                                                self.card_dmg_pct))
                    if buff:
                        self._apply_buff(u, buff, btime or 1000, p.team)
            sub = pdef.get("SpawnAreaEffectObject")
            if isinstance(sub, str):
                ae = self.aeo.get(sub)
                if ae:
                    self._spawn_area_field(sub, ae, p.team, p.tx, p.ty)
            subp = pdef.get("SpawnProjectile")
            if isinstance(subp, str):
                ang = p.angle
                self._spawn_chain_projectiles(pdef, subp, p.team,
                                              p.tx, p.ty, 0, p.chain_depth + 1,
                                              ang)
        if p.spawn_character:
            for i in range(p.spawn_count or 1):
                u = self._place(p.spawn_character, p.team,
                                p.tx + (i - (p.spawn_count - 1) / 2.0) * 0.5, p.ty)
                if u:
                    u.load_ms = p.spawn_delay_ms or 1000

