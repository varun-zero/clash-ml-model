    def _bar_ms(self) -> float:
        if self.t < 120_000:
            return float(self._tl_rows[0].get("ElixirFullBarMS") or 28000)
        if self.t < NORMAL_MS + 60_000:
            return float((self._tl_rows[1] or {}).get("ElixirFullBarMS") or 14000)
        return float((self._tl_rows[-1] or {}).get("ElixirFullBarMS") or 9300)

    def _check_end(self):
        if self.t >= MATCH_CAP_MS:
            self._end()
        elif self.t >= NORMAL_MS and not self._overtime_started:
            if self.crowns[0] != self.crowns[1]:
                self._end()
            else:
                self._overtime_started = True
                self.events.append((self.t, "overtime"))
        elif self._overtime_started and self.crowns[0] != self.crowns[1]:
            self._end()

    def _end(self):
        self.done = True
        if self.crowns[0] != self.crowns[1]:
            self.result = 0 if self.crowns[0] > self.crowns[1] else 1
        else:
            # Official Clash Royale Sudden-Death Tiebreaker: Compare lowest-HP active towers
            t0_hps = [u.hp for u in self.units if isinstance(u, Tower) and u.team == 0 and u.hp > 0]
            t1_hps = [u.hp for u in self.units if isinstance(u, Tower) and u.team == 1 and u.hp > 0]
            min0 = min(t0_hps) if t0_hps else 0
            min1 = min(t1_hps) if t1_hps else 0
            if min0 > min1:
                self.result = 0
            elif min1 > min0:
                self.result = 1
            else:
                self.result = None
        self.events.append((self.t, f"end result={self.result}"))
