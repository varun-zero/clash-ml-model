"""Headless Clash Royale rules engine (v1 — full-card behavior).

Pure-Python tick engine parameterized by `data/logic.json`, generated by
tools/load_logic.py from the game's decoded logic tables.

Conventions (derived from asset data; see README):
  * Arena 18x32 tiles, blue low-y / red high-y, mirror (x,y)->(18-x,32-y).
  * Spawn map coords use 2 units/tile; ranges & radii use 1000/tile.
  * Speed u -> tiles/s = 0.0125 * u.
  * Projectile Speed u -> tiles/s = u / 100 (princess arrow 600 -> 6 t/s).
  * Time in ms; default tick 100ms.
  * Elixir: start 6, 28s/bar normal, 14s OT, 9.3s extra, 1s card cooldown.
  * Level scaling: cards +10%/lvl (hp&dmg), king hp +7% dmg +8%,
    princess +8%/8%; from lvl 11 -> 10% steps (globals.csv).
  * Attacks are edge-to-edge: center distance <= range + col_a + col_b.

Behavior coverage (data-driven, per card rows / character defs):
  flying, air/ground targeting, target-only-buildings, min range,
  AoE melee splash (AreaDamageRadius), projectile travel + splash
  (Radius/AoeToAir/AoeToGround/Homing), charge (ChargeRange/
  ChargeSpeedMultiplier, x2 charged damage), dash (DashDamage/
  DashMaxRange/DashCooldown), river jump (JumpEnabled), kamikaze,
  shields (ShieldHitpoints), death spawns, death area effects,
  spawner buildings (SpawnCharacter/SpawnNumber/SpawnPauseTime/
  SpawnStartTime/SpawnLimit), elixir production (ManaCollectAmount /
  ManaGenerateTimeMs), damage ramp (VariableDamage2/3 + times, inferno
  family), knockback (AttackPushBack/IgnorePushback), spell fields
  (AreaEffectObject: Zap/Freeze/Poison/Graveyard/Tornado/Earthquake/
  Lightning/RoyalDelivery/Rage), spell projectile spawns (GoblinBarrel,
  RoyalDelivery), Mirror replay, crown-tower damage percentages.

Still approximated (documented): pathing is waypoint-straight (no local
avoidance), no unit-unit pushback mass physics, evolutions behave as their
EXT stat block without unique scripts, a few champion abilities and
invisibility/fisherman mechanics are stubs.
"""
