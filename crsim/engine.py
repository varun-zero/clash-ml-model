def load_model(path: str | None = None) -> dict:
    here = pathlib.Path(__file__).resolve().parent.parent
    with open(pathlib.Path(path) if path else here / "data" / "logic.json",
              encoding="utf-8") as f:
        return json.load(f)


def _seg_dist(px: float, py: float, nx: float, ny: float,
              ux: float, uy: float) -> float:
    """Shortest distance from a point to a swept segment (anti-tunneling)."""
    sx, sy = nx - px, ny - py
    ln2 = sx * sx + sy * sy
    if ln2 < 1e-12:
        return math.hypot(ux - px, uy - py)
    t = max(0.0, min(1.0, ((ux - px) * sx + (uy - py) * sy) / ln2))
    return math.hypot(ux - (px + t * sx), uy - (py + t * sy))


def _growth(base: float, level: int, pct: float) -> int:
    v = float(base)
    for i in range(1, level):
        v *= (1.0 + (pct if i < 11 else 10.0) / 100.0)
    return int(v + 0.5)


_VARIANT_SUFFIX = re.compile(r"_(?:(?:XXLarge|XLarge|Large|Medium|Small)|lv\d+)$")


def _pick_buff_variants(names: list) -> list:
    """Collapse size/level variants of the same buff, keeping distinct buffs.

    Vines exposes one snare buff per target size (identical stats), DarkMagic
    one damage buff per card level.  GoblinCurse and GoblinCurseDamage are
    different buffs and both must survive.
    """
    groups: dict[str, list] = {}
    order: list[str] = []
    for n in names:
        if not isinstance(n, str) or not n:
            continue
        key = _VARIANT_SUFFIX.sub("", n)
        if key not in groups:
            groups[key] = []
            order.append(key)
        groups[key].append(n)
    out = []
    for key in order:
        opts = groups[key]
        if len(opts) == 1:
            out.append(opts[0])
            continue
        med = next((o for o in opts if o.endswith("_Medium")), None)
        if med:
            out.append(med)
            continue
        opts.sort(key=lambda o: int(o.rsplit("lv", 1)[1])
                  if o.rsplit("lv", 1)[-1].isdigit() else 0)
        out.append(opts[-1])
    return out


def _num(v, default=0):
    return v if isinstance(v, (int, float)) else default


